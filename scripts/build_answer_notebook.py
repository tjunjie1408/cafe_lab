TITLE = (
    "# # Causal Cafe Lab - Growth Intelligence Team",
    "# # Causal Cafe Lab - Answer Notebook (facilitator only)\n"
    "# Generated by scripts/build_answer_notebook.py from workshop.py: the four TODOs\n"
    "# are filled in, nothing else changes. Do not put this file on `main`.",
)


def build_answers(source: str) -> str:
    for todo, answer in [TITLE, *ANSWERS]:
        if source.count(todo) != 1:
            raise ValueError(f"expected exactly one match for:\n{todo}")
        source = source.replace(todo, answer)
    if "raise NotImplementedError" in source:
        raise ValueError("workshop.py has a TODO this script does not answer")
    return source


def main() -> None:
    TARGET.write_text(build_answers(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"Answer source -> {TARGET.relative_to(PROJECT_ROOT)}")
    try:
        import jupytext
    except ImportError:
        print("jupytext unavailable: run `python -m jupytext --to ipynb` on the file yourself.")
    else:
        from jupytext.combine import combine_inputs_with_outputs

        notebook_path = TARGET.with_suffix(".ipynb")
        notebook = jupytext.read(TARGET)
        if notebook_path.exists():
            notebook = combine_inputs_with_outputs(notebook, jupytext.read(notebook_path))
        jupytext.write(notebook, notebook_path)


if __name__ == "__main__":
    main()
